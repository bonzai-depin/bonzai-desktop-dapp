export function billingText(source, locale = "fr") {
  if (String(locale).startsWith("fr")) return source;
  if (en[source]) return en[source];
  if (typeof source === "string" && source.includes("\n"))
    return source
      .split("\n")
      .map((line) => billingText(line, locale))
      .join("\n");
  if (
    typeof source === "string" &&
    source.startsWith("Service fait manquant :")
  )
    return source.replace(
      "Service fait manquant :",
      "Service acceptance missing:",
    );
  if (
    typeof source === "string" &&
    source.startsWith("Transmission facturation à valider :")
  )
    return source.replace(
      "Transmission facturation à valider :",
      "Billing handoff requires validation:",
    );
  return source;
}
