/**
 * BonzAI MintPool — Chainlink CRE Workflow
 *
 * Watches for RegistrationRequested and ConfirmClaimRequested events on Base,
 * fetches BONZAI balances on Ethereum and Arbitrum, and delivers the
 * cross-chain total back to BonzaiMintPool via the CRE Forwarder.
 *
 * The contract adds the on-chain Base balance itself — the workflow only
 * reports the ETH + ARB portion.
 *
 * ─── Setup ─────────────────────────────────────────────────
 *
 * 1. Install CRE CLI:
 *    curl -LO https://github.com/smartcontractkit/cre-cli/releases/download/v1.10.0/cre_darwin_arm64.zip
 *    unzip cre_darwin_arm64.zip && sudo mv cre /usr/local/bin/
 *
 * 2. Generate TypeScript bindings from the BonzaiMintPool ABI:
 *    cre generate --abi ../BonzaiMintPool.json --out ./generated --lang ts
 *
 *    This creates BonzaiMintPool.ts with typed methods:
 *    - logTriggerRegistrationRequested()
 *    - logTriggerConfirmClaimRequested()
 *    - writeReport(runtime, callData)
 *
 * 3. Install dependencies:
 *    bun add @chainlink/cre-sdk viem zod
 *
 * 4. Simulate:
 *    cre workflow simulate
 *
 * 5. Deploy:
 *    cre deploy --network base-mainnet
 */

import {
	cre,
	getNetwork,
	TxStatus,
	bytesToHex,
	type Runtime,
} from '@chainlink/cre-sdk'
import {
	type Address,
	encodeAbiParameters,
	parseAbiParameters,
	hexToBigInt,
} from 'viem'
import { z } from 'zod'
// Generated by: cre generate --abi ../BonzaiMintPool.json --out ./generated --lang ts
import {
	BonzaiMintPool,
	type DecodedLog,
	type RegistrationRequestedDecoded,
	type ConfirmClaimRequestedDecoded,
} from './generated/BonzaiMintPool'

// ─── Config ────────────────────────────────────────────────
export const configSchema = z.object({
	chainSelectorName: z.string(), // "base-mainnet"
	mintPoolAddress: z.string(),   // BonzaiMintPool contract on Base
})
type Config = z.infer<typeof configSchema>

// BONZAI token addresses
const BONZAI_ETH = '0xDdA9Ff241C7160be8295EF9Eca2e782361467666'
const BONZAI_ARB = '0x0a84edf70f30325151631ce7a61307d1f4d619a3'
const BALANCE_OF_SELECTOR = '0x70a08231'

// ─── Fetch cross-chain BONZAI balance ──────────────────────
function fetchCrossChainBalance(
	runtime: Runtime<Config>,
	userAddress: string,
): bigint {
	const httpClient = new cre.capabilities.HTTPClient()
	const paddedAddress = userAddress.slice(2).padStart(64, '0')
	const calldata = BALANCE_OF_SELECTOR + paddedAddress

	const ethResponse = httpClient.post(runtime, 'https://ethereum.publicnode.com', {
		body: JSON.stringify({
			jsonrpc: '2.0', method: 'eth_call',
			params: [{ to: BONZAI_ETH, data: calldata }, 'latest'], id: 1,
		}),
		headers: { 'Content-Type': 'application/json' },
	})

	const arbResponse = httpClient.post(runtime, 'https://arbitrum.publicnode.com', {
		body: JSON.stringify({
			jsonrpc: '2.0', method: 'eth_call',
			params: [{ to: BONZAI_ARB, data: calldata }, 'latest'], id: 1,
		}),
		headers: { 'Content-Type': 'application/json' },
	})

	const ethBal = hexToBigInt((JSON.parse(ethResponse.body).result || '0x0') as `0x${string}`)
	const arbBal = hexToBigInt((JSON.parse(arbResponse.body).result || '0x0') as `0x${string}`)

	runtime.log(`Cross-chain balance for ${userAddress}: ETH=${ethBal}, ARB=${arbBal}`)
	return ethBal + arbBal
}

// ─── Handle RegistrationRequested ──────────────────────────
export const onRegistrationRequested = (
	runtime: Runtime<Config>,
	payload: DecodedLog<RegistrationRequestedDecoded>,
): string => {
	const wallet = payload.data.wallet
	runtime.log(`Registration requested: ${wallet}`)

	const crossChainBalance = fetchCrossChainBalance(runtime, wallet)

	// Encode report: (address user, uint256 crossChainBalance)
	const reportData = encodeAbiParameters(
		parseAbiParameters('address user, uint256 crossChainBalance'),
		[wallet, crossChainBalance],
	)

	// Deliver report via forwarder → mintPool.onReport()
	const pool = getPool(runtime.config)
	const result = pool.writeReport(runtime, reportData)

	if (result.txStatus !== TxStatus.SUCCESS) {
		throw new Error(`Report failed: ${result.errorMessage || result.txStatus}`)
	}

	const txHash = bytesToHex(result.txHash || new Uint8Array(32))
	runtime.log(`Registration delivered: ${txHash}`)
	return `Registered ${wallet}, cross-chain=${crossChainBalance}`
}

// ─── Handle ConfirmClaimRequested ──────────────────────────
export const onConfirmClaimRequested = (
	runtime: Runtime<Config>,
	payload: DecodedLog<ConfirmClaimRequestedDecoded>,
): string => {
	const wallet = payload.data.wallet
	runtime.log(`Confirm claim requested: ${wallet}`)

	const crossChainBalance = fetchCrossChainBalance(runtime, wallet)

	const reportData = encodeAbiParameters(
		parseAbiParameters('address user, uint256 crossChainBalance'),
		[wallet, crossChainBalance],
	)

	const pool = getPool(runtime.config)
	const result = pool.writeReport(runtime, reportData)

	if (result.txStatus !== TxStatus.SUCCESS) {
		throw new Error(`Report failed: ${result.errorMessage || result.txStatus}`)
	}

	const txHash = bytesToHex(result.txHash || new Uint8Array(32))
	runtime.log(`Confirm claim delivered: ${txHash}`)
	return `Confirmed ${wallet}, cross-chain=${crossChainBalance}`
}

// ─── Helper ────────────────────────────────────────────────
function getPool(config: Config): BonzaiMintPool {
	const network = getNetwork({
		chainFamily: 'evm',
		chainSelectorName: config.chainSelectorName,
		isTestnet: false,
	})
	if (!network) throw new Error(`Network not found: ${config.chainSelectorName}`)

	const evmClient = new cre.capabilities.EVMClient(network.chainSelector.selector)
	return new BonzaiMintPool(evmClient, config.mintPoolAddress as Address)
}

// ─── Workflow Init ─────────────────────────────────────────
export function initWorkflow(config: Config) {
	const pool = getPool(config)

	return [
		// Watch for RegistrationRequested events → fetch balances → deliver report
		cre.handler(
			pool.logTriggerRegistrationRequested(),
			onRegistrationRequested,
		),
		// Watch for ConfirmClaimRequested events → fetch balances → deliver report
		cre.handler(
			pool.logTriggerConfirmClaimRequested(),
			onConfirmClaimRequested,
		),
	]
}
