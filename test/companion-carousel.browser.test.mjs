import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const url = process.env.BONZAI_UI_URL;
test('companion carousel browses with arrows without committing selection and preserves the existing choose action', {skip: !url, timeout:60000}, async()=>{
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 try {
  const page=await browser.newPage({viewport:{width:1280,height:1000}});
  page.setDefaultTimeout(10000);
  await page.goto(new URL('/src/assets/tokens.css',url).href);
  await page.setContent('<link rel="stylesheet" href="/src/assets/tokens.css"><link rel="stylesheet" href="/src/assets/themes.css"><link rel="stylesheet" href="/src/assets/buttons.css"><link rel="stylesheet" href="/src/assets/fonts/fonts.css"><style>body{margin:0;padding:24px;background:var(--bz-canvas)}#test{max-width:1100px;margin:auto}</style><div id="test"></div>');
  await page.route('**/pipelines/plan', route => route.fulfill({json:{ok:false}}));
  await page.route('**/pipelines/prefetch', route => route.fulfill({json:{ok:true}}));
  await page.evaluate(async()=>{
   const {createApp,h}=await import('/node_modules/.vite/deps/vue.js');
   const storeSource = await (await fetch('/src/stores/web3.store.js')).text();
   const piniaUrl = storeSource.match(/from ["']([^"']*pinia[^"']*)["']/)[1];
   const {createPinia}=await import(piniaUrl);
   const {default:Roleplay}=await import('/src/components/skills/RoleplayChat.vue');
   const {roleplayCompanion}=await import('/src/skills/flagship.js');
   const {createI18nPlugin}=await import('/src/i18n/index.js');
   window.chosen=[];
   window.carouselApp=createApp({render:()=>h(Roleplay,{skill:roleplayCompanion,onCompanionSelected:c=>window.chosen.push(c.id)})}).use(createPinia()).use(createI18nPlugin());
   window.carouselApp.mount('#test');
  });
  const selector=page.getByRole('region',{name:'Companion selector'});
  await selector.waitFor();
  const portraits=selector.locator('.companion-selector__portrait');
  await portraits.first().waitFor();
  assert.ok(await portraits.count()>1);
  assert.equal(await selector.locator('.companion-card').count(),1);
  const first=await portraits.first().getAttribute('aria-label');
  await selector.getByRole('button',{name:'Next companion',exact:true}).click();
  const second=await portraits.nth(1).getAttribute('aria-label');
  assert.notEqual(first,second);
  assert.equal(await portraits.nth(1).getAttribute('aria-pressed'),'true');
  assert.deepEqual(await page.evaluate(()=>window.chosen),[]);
  await portraits.nth(1).focus();
  await page.keyboard.press('ArrowLeft');
  await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-pressed')==='true');
  assert.equal(await portraits.first().getAttribute('aria-pressed'),'true');
  await selector.getByRole('button',{name:'Choose companion',exact:true}).click();
  assert.equal((await page.evaluate(()=>window.chosen)).length,1);
  await selector.getByRole('button',{name:'Selected',exact:true}).waitFor();
  assert.equal(await selector.locator('.companion-workflow-skills').count(), 0);
  assert.ok(await selector.locator('canvas').evaluate(el => el.getBoundingClientRect().width) > 300);
  const stages = page.getByRole('region', {name:'Scenario selector'});
  assert.equal(await stages.locator('.scenario-card').count(), 1);
  await stages.getByRole('button', {name:'Next scenario', exact:true}).click();
  assert.equal(await stages.locator('.stage-tile').nth(1).getAttribute('aria-pressed'), 'true');
  await stages.getByRole('button', {name:'Choose stage', exact:true}).click();
  await stages.getByRole('button', {name:'Selected stage', exact:true}).waitFor();
  const ratings = page.locator('button.content-level-option');
  await ratings.nth(1).click();
  assert.equal(await ratings.nth(1).getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('button.media-option').count(), 4);
  const imageMedia = page.locator('button.media-option').first();
  assert.equal(await imageMedia.isDisabled(), true);
  await page.getByRole('region', {name:'Enable scene images'}).getByRole('button', {name:'Download', exact:true}).click();
  await page.waitForFunction(() => !document.querySelector('button.media-option').disabled);
  assert.equal(await imageMedia.getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('button.media-option').nth(1).isDisabled(), true);
  await page.getByRole('textbox', {name:'Your role in the story'}).fill('A visiting researcher.');
  await page.getByLabel('Character name', {exact:true}).fill('Alex');
  await page.getByLabel('Backstory', {exact:true}).fill('Returning to the archive after years away.');
  await page.getByLabel('Motivation', {exact:true}).fill('Find the missing letter.');
  await page.getByLabel('Motivation', {exact:true}).blur();
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('roleplayUserProfile')).goals), 'Find the missing letter.');
  assert.equal(await page.locator('.roleplay-settings').first().evaluate(el => getComputedStyle(el).padding), await page.locator('.models__activity--payouts').first().evaluate(el => getComputedStyle(el).padding));
  for(const width of [1280,600]){
   await page.setViewportSize({width,height:1000});
   assert.ok(await selector.evaluate(el=>el.scrollWidth<=el.clientWidth+1));
   assert.ok(await stages.evaluate(el=>el.scrollWidth<=el.clientWidth+1));
   assert.ok(await page.locator('.role-profile-grid').evaluate(el => el.scrollWidth <= el.clientWidth + 1));
   if (process.env.BONZAI_UI_SCREENSHOTS) await page.locator('.user-profile-section').screenshot({path:`/tmp/role-profile-${width}.png`});
  }
  await page.evaluate(()=>window.carouselApp.unmount());
 } finally {await browser.close();}
});
